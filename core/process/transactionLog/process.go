var _ process.TransactionLogProcessor = (*txLogProcessor)(nil)

var log = logger.GetOrCreate("process/transactionLog")

// multiEpochRemover is implemented by storers that keep one persister per epoch
type multiEpochRemover interface {
	RemoveFromAllActivePersisters(key []byte) error
}

// ArgTxLogProcessor defines the arguments needed for transaction logs processor
type ArgTxLogProcessor struct {
	Storer               storage.Storer
	Marshalizer          marshal.Marshalizer
	SaveInStorageEnabled bool
}

type txLogProcessor struct {
	logs        []*data.LogData
	logsIndices map[string]int
	// discarded txs whose stored log (e.g. from a rolled-back block) is deleted at commit
	pendingRemovals map[string]struct{}
	mut             sync.RWMutex
	storer          storage.Storer
	marshalizer     marshal.Marshalizer
}

// NewTxLogProcessor creates a transaction log processor capable of parsing logs from the VM
//
//	and saving them into the injected storage
func NewTxLogProcessor(args ArgTxLogProcessor) (*txLogProcessor, error) {
	storer := args.Storer
	if check.IfNil(storer) && args.SaveInStorageEnabled {
		return nil, process.ErrNilStore
	}

	if !args.SaveInStorageEnabled {
		storer = storageUnit.NewNilStorer()
	}

	if check.IfNil(args.Marshalizer) {
		return nil, process.ErrNilMarshalizer
	}

	return &txLogProcessor{
		storer:          storer,
		marshalizer:     args.Marshalizer,
		logs:            make([]*data.LogData, 0),
		logsIndices:     make(map[string]int),
		pendingRemovals: make(map[string]struct{}),
		mut:             sync.RWMutex{},
	}, nil
}

// GetLog retrieves a log generated by a transaction
func (tlp *txLogProcessor) GetLog(txHash []byte) (data.LogHandler, error) {
	tlp.mut.RLock()
	defer tlp.mut.RUnlock()

	index, ok := tlp.logsIndices[string(txHash)]
	if ok {
		return tlp.logs[index], nil
	}
	// in-process callers only; the API reads the storer directly
	if _, removed := tlp.pendingRemovals[string(txHash)]; removed {
		return nil, process.ErrLogNotFound
	}

	txLogBuff, err := tlp.storer.Get(txHash)
	if err != nil {
		return nil, process.ErrLogNotFound
	}

	var txLog transaction.Log
	err = tlp.marshalizer.Unmarshal(&txLog, txLogBuff)
	if err != nil {
		return nil, err
	}

	return &txLog, nil
}

// GetLogFromCache retrieves a log generated by a transaction from ram or from storage
// TODO remove this function and change the interface no longer needed
func (tlp *txLogProcessor) GetLogFromCache(txHash []byte) (*data.LogData, bool) {
	tlp.mut.RLock()
	defer tlp.mut.RUnlock()

	index, ok := tlp.logsIndices[string(txHash)]
	if ok {
		return tlp.logs[index], true
	}

	txLog, err := tlp.GetLog(txHash)
	if err != nil {
		return nil, false
	}

	return &data.LogData{
		LogHandler: txLog,
		TxHash:     string(txHash),
	}, true
}

// GetAllCurrentLogs will return all generated logs for the current block
func (tlp *txLogProcessor) GetAllCurrentLogs() []*data.LogData {
	tlp.mut.RLock()
	logsSlice := make([]*data.LogData, 0, len(tlp.logs))
	logsSlice = append(logsSlice, tlp.logs...)
	tlp.mut.RUnlock()

	return logsSlice
}

// EnableLogToBeSavedInCache will set a flag with true and txLogProcessor will start saving transactions logs also in RAM
func (tlp *txLogProcessor) EnableLogToBeSavedInCache() {
}

// Clean will remove all transaction logs from RAM memory
func (tlp *txLogProcessor) Clean() {
	tlp.mut.Lock()
	tlp.logsIndices = make(map[string]int)
	tlp.logs = make([]*data.LogData, 0)
	tlp.pendingRemovals = make(map[string]struct{})
	tlp.mut.Unlock()
}

// SaveLog converts the VM logs and stages them in the RAM cache for the current block:
// SaveLogsToStorage persists them from CommitBlock, and Clean discards a rejected block's logs
func (tlp *txLogProcessor) SaveLog(txHash []byte, acntSender []byte, tc data.SmartContractHandler, contractID int, logEntries []*vmcommon.LogEntry) error {
	if len(txHash) == 0 {
		return process.ErrNilTxHash
	}

	if len(logEntries) == 0 {
		log.Trace("txLogProcessor.SaveLog()",
			"txHash", hex.EncodeToString(txHash),
			"message", "no logEntries provided",
		)

		return nil
	}

	txLog := &transaction.Log{
		Address:    getLogAddressByTx(acntSender, tc),
		ContractID: int32(contractID), // #nosec G115 - limited contract per TX
	}

	for _, logEntry := range logEntries {
		txLog.Events = append(txLog.Events, &transaction.Event{
			Identifier:  logEntry.Identifier,
			Address:     logEntry.Address,
			Topics:      logEntry.Topics,
			Data:        logEntry.Data,
			IsSystemLog: logEntry.IsSystemLog,
		})
	}

	// Cache only; SaveLogsToStorage persists after the block passes validation.
	tlp.saveLogToCache(txHash, txLog)

	return nil
}

// SaveLogsToStorage deletes the stored logs of discarded txs and persists the logs cached
// for the current block. CommitBlock calls it once the block has passed validation. A
// failed remove or write does not stop the rest; the first error is returned.
func (tlp *txLogProcessor) SaveLogsToStorage() error {
	// snapshot under the lock and do the I/O after; block processing is sequential
	tlp.mut.RLock()
	removals := make([][]byte, 0, len(tlp.pendingRemovals))
	for key := range tlp.pendingRemovals {
		removals = append(removals, []byte(key))
	}
	logs := make([]*data.LogData, 0, len(tlp.logs))
	logs = append(logs, tlp.logs...)
	tlp.mut.RUnlock()

	var firstErr error
	// removing a missing key is not an error, so any error here is a storage failure
	for _, key := range removals {
		if err := tlp.removeStoredLog(key); err != nil && firstErr == nil {
			firstErr = err
		}
	}

	for _, logData := range logs {
		buff, err := tlp.marshalizer.Marshal(logData.LogHandler)
		if err == nil {
			err = tlp.storer.Put([]byte(logData.TxHash), buff)
		}
		if err != nil && firstErr == nil {
			firstErr = err
		}
	}

	return firstErr
}

// removeStoredLog deletes the log from every epoch; a pruning storer's Remove only reaches the newest
func (tlp *txLogProcessor) removeStoredLog(key []byte) error {
	if remover, ok := tlp.storer.(multiEpochRemover); ok {
		return remover.RemoveFromAllActivePersisters(key)
	}

	return tlp.storer.Remove(key)
}

// RemoveLog drops every cached log of a tx and stages the removal of its stored log,
// applied by SaveLogsToStorage at commit; an empty hash is a no-op
func (tlp *txLogProcessor) RemoveLog(txHash []byte) {
	if len(txHash) == 0 {
		return
	}
	key := string(txHash)

	tlp.mut.Lock()
	defer tlp.mut.Unlock()

	tlp.pendingRemovals[key] = struct{}{}
	if _, ok := tlp.logsIndices[key]; !ok {
		return
	}

	kept := make([]*data.LogData, 0, len(tlp.logs))
	indices := make(map[string]int, len(tlp.logsIndices))
	for _, logData := range tlp.logs {
		if logData.TxHash == key {
			continue
		}
		kept = append(kept, logData)
		indices[logData.TxHash] = len(kept) - 1
	}

	tlp.logs = kept
	tlp.logsIndices = indices
}

func (tlp *txLogProcessor) saveLogToCache(txHash []byte, log *transaction.Log) {
	tlp.mut.Lock()
	tlp.logs = append(tlp.logs, &data.LogData{
		TxHash:     string(txHash),
		LogHandler: log,
	})
	tlp.logsIndices[string(txHash)] = len(tlp.logs) - 1
	delete(tlp.pendingRemovals, string(txHash))
	tlp.mut.Unlock()
}

// For SC deployment transactions, we use the sender address
func getLogAddressByTx(acntSender []byte, tc data.SmartContractHandler) []byte {
	if core.IsEmptyAddress(tc.GetAddress()) {
		return acntSender
	}

	return tc.GetAddress()
}

// IsInterfaceNil returns true if there is no value under the interface
func (tlp *txLogProcessor) IsInterfaceNil() bool {
	return tlp == nil
}
