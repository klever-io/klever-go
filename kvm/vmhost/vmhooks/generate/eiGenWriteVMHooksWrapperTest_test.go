func TestGetFunctionSignature(t *testing.T) {
	var testCases = []struct {
		name     string
		function *EIFunction
		expected string
	}{
		{
			name:     "No arguments, no return",
			function: &EIFunction{},
			expected: "()",
		},
		{
			name: "No arguments, return",
			function: &EIFunction{
				Result: &EIFunctionResult{
					Type: EITypeInt32,
				},
			},
			expected: "() int32",
		},
		{
			name: "4 arguments, no return",
			function: &EIFunction{
				Arguments: []*EIFunctionArg{
					{
						Name: "arg1",
						Type: EITypeInt32,
					},
					{
						Name: "arg2",
						Type: EITypeInt64,
					},
					{
						Name: "arg3",
						Type: EITypeMemPtr,
					},
					{
						Name: "arg4",
						Type: EITypeMemLength,
					},
				},
			},
			expected: "(arg1 int32, arg2 int64, arg3 executor.MemPtr, arg4 executor.MemLength)",
		},
		{
			name: "4 arguments, return",
			function: &EIFunction{
				Arguments: []*EIFunctionArg{
					{
						Name: "arg1",
						Type: EITypeInt32,
					},
					{
						Name: "arg2",
						Type: EITypeInt64,
					},
					{
						Name: "arg3",
						Type: EITypeMemPtr,
					},
					{
						Name: "arg4",
						Type: EITypeMemLength,
					},
				},
				Result: &EIFunctionResult{
					Type: EITypeInt32,
				},
			},
			expected: "(arg1 int32, arg2 int64, arg3 executor.MemPtr, arg4 executor.MemLength) int32",
		},
	}
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			actual := getFunctionSignature(tc.function)
			if actual != tc.expected {
				t.Errorf("Expected %s, got %s", tc.expected, actual)
			}
		})
	}
}

