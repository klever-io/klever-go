func TestBuildVMWrapperFunctionTest(t *testing.T) {
	var testCases = []struct {
		name     string
		function *EIFunction
		expected string
	}{
		{
			name: "No arguments, no return",
			function: &EIFunction{
				Name: "NoArgsNoReturn",
			},
			expected: `func TestNoArgsNoReturn(t *testing.T) {
	var testCases = []struct {
		name        string
		shouldPanic bool
		shouldCall  bool
		delay       time.Duration
		timeout     time.Duration
	}{
		{
			name:        "NoArgsNoReturn should call hook",
			shouldPanic: false,
			shouldCall:  true,
			delay:       0,
			timeout:     time.Second * 1,
		},
		{
			name:        "NoArgsNoReturn should timeout",
			shouldPanic: true,
			shouldCall:  true,
			delay:       time.Millisecond * 10,
			timeout:     0,
		},
	}
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			called := false
			panicked := false
			defer func() {
				r := recover()
				panicked = r != nil
			}()
			wrapper := NewWrapperVMHooks(&stub.VMHooksStub{
				NoArgsNoReturnCalled: func () {
					called = true
					time.Sleep(tc.delay)
					return
				},
			}, &NoLogger{}, tc.timeout)
			wrapper.NoArgsNoReturn()
			assert.Equal(t, tc.shouldCall, called)
			assert.Equal(t, tc.shouldPanic, panicked)
		})
	}
}

`,
		},
		{
			name: "2 arguments, return",
			function: &EIFunction{
				Name: "TwoArgsWithReturn",
				Arguments: []*EIFunctionArg{
					{
						Name: "arg1",
						Type: EITypeInt32,
					},
					{
						Name: "arg2",
						Type: EITypeMemPtr,
					},
				},
				Result: &EIFunctionResult{
					Type: EITypeInt32,
				},
			},
			expected: `func TestTwoArgsWithReturn(t *testing.T) {
	var testCases = []struct {
		name        string
		shouldPanic bool
		shouldCall  bool
		delay       time.Duration
		timeout     time.Duration
	}{
		{
			name:        "TwoArgsWithReturn should call hook",
			shouldPanic: false,
			shouldCall:  true,
			delay:       0,
			timeout:     time.Second * 1,
		},
		{
			name:        "TwoArgsWithReturn should timeout",
			shouldPanic: true,
			shouldCall:  true,
			delay:       time.Millisecond * 10,
			timeout:     0,
		},
	}
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			called := false
			panicked := false
			defer func() {
				r := recover()
				panicked = r != nil
			}()
			wrapper := NewWrapperVMHooks(&stub.VMHooksStub{
				TwoArgsWithReturnCalled: func (arg1 int32, arg2 executor.MemPtr) int32 {
					called = true
					time.Sleep(tc.delay)
					return 0
				},
			}, &NoLogger{}, tc.timeout)
			wrapper.TwoArgsWithReturn(0, 0)
			assert.Equal(t, tc.shouldCall, called)
			assert.Equal(t, tc.shouldPanic, panicked)
		})
	}
}

`,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			actual := buildVMWrapperFunctionTest(tc.function)
			assert.Equal(t, tc.expected, actual)
		})
	}
}
