package vmhooksgenerate

import "fmt"

func WriteVMHooksWrapperTest(out *eiGenWriter, eiMetadata *EIMetadata) {
	out.WriteString(getVMWrapperTestFileHeader())

	for _, funcMetadata := range eiMetadata.AllFunctions {
		out.WriteString(buildVMWrapperFunctionTest(funcMetadata))
	}
}

func buildVMWrapperFunctionTest(function *EIFunction) string {
	return fmt.Sprintf(`func Test%s(t *testing.T) {
	var testCases = []struct {
		name        string
		shouldPanic bool
		shouldCall  bool
		delay       time.Duration
		timeout     time.Duration
	}{
		{
			name:        "%[1]s should call hook",
			shouldPanic: false,
			shouldCall:  true,
			delay:       0,
			timeout:     time.Second * 1,
		},
		{
			name:        "%[1]s should timeout",
			shouldPanic: true,
			shouldCall:  true,
			delay:       time.Millisecond * 10,
			timeout:     0,
		},
	}
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			called := false
			panicked := false
			defer func() {
				r := recover()
				panicked = r != nil
			}()
			wrapper := NewWrapperVMHooks(&stub.VMHooksStub{
				%[1]sCalled: func %[2]s {
					called = true
					time.Sleep(tc.delay)
					%[3]s
				},
			}, &NoLogger{}, tc.timeout)
			wrapper.%[1]s%[4]s
			assert.Equal(t, tc.shouldCall, called)
			assert.Equal(t, tc.shouldPanic, panicked)
		})
	}
}

`,
		upperInitial(function.Name),
		getFunctionSignature(function),
		getDummyFunctionReturn(function),
		getDummyFunctionCallArguments(function))
}

func getVMWrapperTestFileHeader() string {
	return `package executorwrapper

// Code generated by vmhooks generator. DO NOT EDIT.

// !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
// !!!!!!!!!!!!!!!!!!!!!! AUTO-GENERATED FILE !!!!!!!!!!!!!!!!!!!!!!
// !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

import (
	"github.com/klever-io/klever-go/kvm/executor"
	"testing"
	"time"

	"github.com/stretchr/testify/assert"

	"github.com/klever-io/klever-go/kvm/mock/stub"
)

`
}

func getFunctionSignature(function *EIFunction) string {
	signature := "("
	for argIndex, arg := range function.Arguments {
		if argIndex > 0 {
			signature += ", "
		}
		signature += fmt.Sprintf("%s %s", arg.Name, vmHooksWrapperType(arg.Type))
	}
	signature += ")"
	if function.Result != nil {
		signature += fmt.Sprintf(" %s", vmHooksWrapperType(function.Result.Type))
	}
	return signature
}

func getDummyFunctionReturn(function *EIFunction) string {
	if function.Result != nil {
		return fmt.Sprintf("return %s", getInitializedWrapperType(function.Result.Type))
	}
	return "return"
}

func getDummyFunctionCallArguments(function *EIFunction) string {
	signature := "("
	for argIndex, arg := range function.Arguments {
		if argIndex > 0 {
			signature += ", "
		}
		signature += getInitializedWrapperType(arg.Type)
	}
	signature += ")"
	return signature
}

func getInitializedWrapperType(eiType EIType) string {
	switch eiType {
	case EITypeInt32:
		return "0"
	case EITypeInt64:
		return "0"
	case EITypeMemPtr:
		return "0"
	case EITypeMemLength:
		return "0"
	default:
		panic("unhandled default case")
	}
}
